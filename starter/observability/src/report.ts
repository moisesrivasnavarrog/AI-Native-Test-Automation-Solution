/**
 * Static Markdown report generator.
 *
 * The report is deliberately honest about absence of data: insufficient
 * history, non-comparable runs, and partial executions are stated, never
 * smoothed over. It never embeds simulated data.
 */

import type { NormalizedRun } from './contract.ts';
import type { ValidationIssue } from './contract.ts';
import {
  computeRunMetrics,
  computeTestFlakiness,
  computeTrends,
  type RunMetrics,
} from './metrics.ts';

const DEFS: [string, string][] = [
  ['pass rate', 'passed / (passed + failed + flaky) — skipped and unknown are excluded from numerator and denominator; flaky does not count as passed'],
  ['skipped share', 'skipped / total logical tests'],
  ['flaky rate', 'flaky / (passed + failed + flaky) — requires per-attempt data'],
  ['run duration', 'runner-reported stats.duration (wall clock of the test run, not push-to-feedback time)'],
  ['test duration', 'sum of logical test durations across all attempts'],
  ['p50 / p95', 'nearest-rank percentiles over executed-test durations; shown only with ≥5 executed tests'],
  ['trends', 'latest comparable run vs previous comparable run (same project set AND spec files); requires ≥2'],
];

function pct(x: number | null): string {
  return x === null ? 'n/a' : `${(x * 100).toFixed(1)}%`;
}
function ms(x: number | null): string {
  return x === null ? 'n/a' : `${Math.round(x)} ms`;
}
function signedMs(x: number | null): string {
  if (x === null) return 'n/a';
  return `${x >= 0 ? '+' : ''}${Math.round(x)} ms`;
}
function signedPct(x: number | null): string {
  if (x === null) return 'n/a';
  return `${x >= 0 ? '+' : ''}${(x * 100).toFixed(1)}%`;
}
function cell(s: string | null): string {
  return s === null || s === '' ? '—' : s;
}
function esc(s: string): string {
  return s.replace(/\|/g, '\\|');
}
function shortSha(sha: string | null): string {
  return sha === null ? '—' : sha.slice(0, 7);
}

export interface ReportInput {
  runs: NormalizedRun[];
  nonProcessable: { file: string; issues: ValidationIssue[] }[];
  generatedAt: string;
}

export function renderMarkdownReport(input: ReportInput): string {
  const { runs, nonProcessable, generatedAt } = input;
  const out: string[] = [];

  out.push('# Observability Report — Playwright Executions');
  out.push('');
  out.push(`> Generated by \`npm run observe:report\` at ${generatedAt}. Do not edit by hand.`);
  out.push('> Contract: `ai-native-qa/observability` v1 · Definitions: `docs/observability.md`');
  out.push('> Missing data is shown as `—`, `n/a`, or **Insufficient data** — never inferred.');
  out.push('');

  // ---- Scope ----
  const sorted = [...runs].sort((a, b) =>
    (a.run.executedAt ?? a.run.importedAt).localeCompare(b.run.executedAt ?? b.run.importedAt),
  );
  const sources = [...new Set(runs.map((r) => r.run.source))].sort();
  const from = sorted.length > 0 ? (sorted[0].run.executedAt ?? sorted[0].run.importedAt) : null;
  const to = sorted.length > 0 ? (sorted[sorted.length - 1].run.executedAt ?? sorted[sorted.length - 1].run.importedAt) : null;

  out.push('## Scope');
  out.push('');
  out.push(`- Runs in history: **${runs.length}**`);
  out.push(`- Period covered: ${from ?? '—'} → ${to ?? '—'}`);
  out.push(`- Sources: ${sources.length > 0 ? sources.join(', ') : '—'}`);
  out.push(`- Non-processable files: **${nonProcessable.length}**`);
  out.push('');

  if (runs.length === 0) {
    out.push('**Insufficient data** — no normalized runs in history. Import one with `npm run observe:import -- <results.json>`.');
    out.push('');
    return out.join('\n');
  }

  // ---- Per-run table ----
  out.push('## Runs');
  out.push('');
  out.push('| Executed at | runId | Source | Commit | Tests | Pass | Fail | Flaky | Skip | Pass rate | Duration | Completeness | Evidence |');
  out.push('| ----------- | ----- | ------ | ------ | ----- | ---- | ---- | ----- | ---- | --------- | -------- | ------------ | -------- |');
  for (const r of sorted) {
    const m: RunMetrics = computeRunMetrics(r);
    const evidenceBits = [
      r.evidence.htmlReport !== null ? `html: ${r.evidence.htmlReport}` : null,
      r.evidence.artifactName !== null ? `artifact: ${r.evidence.artifactName}` : null,
      r.run.workflow.url !== null ? `run: ${r.run.workflow.url}` : null,
    ].filter((b): b is string => b !== null);
    out.push(
      `| ${cell(r.run.executedAt)} | \`${r.run.runId}\` | ${r.run.source} | ${shortSha(r.run.commitSha)} | ${m.total} | ${m.passed} | ${m.failed} | ${m.flaky} | ${m.skipped} | ${pct(m.passRate)} | ${ms(m.runDurationMs)} | ${r.run.completeness} | ${evidenceBits.length > 0 ? esc(evidenceBits.join('<br>')) : '—'} |`,
    );
  }
  out.push('');

  // ---- Latest-run detail ----
  const latest = sorted[sorted.length - 1];
  const lm = computeRunMetrics(latest);
  out.push('## Latest run');
  out.push('');
  out.push(`- runId: \`${latest.run.runId}\` (${latest.run.source}${latest.run.branch !== null ? `, ${latest.run.branch}` : ''}${latest.run.commitSha !== null ? `, ${latest.run.commitSha.slice(0, 7)}` : ''})`);
  out.push(`- Logical tests: ${lm.total} — passed ${lm.passed}, failed ${lm.failed}, flaky ${lm.flaky}, skipped ${lm.skipped}, unknown ${lm.unknown}`);
  out.push(`- Pass rate: ${pct(lm.passRate)} (denominator: ${lm.executed} executed tests)`);
  out.push(`- Flaky rate: ${pct(lm.flakyRate)} · Skipped share: ${pct(lm.skippedShare)}`);
  out.push(`- Duration: run ${ms(lm.runDurationMs)} · tests Σ ${Math.round(lm.testDurationMs)} ms · p50 ${ms(lm.p50Ms)} · p95 ${ms(lm.p95Ms)}`);
  out.push(`- Completeness: **${latest.run.completeness}**${latest.run.completenessReason !== null ? ` — ${latest.run.completenessReason}` : ''}`);
  if (lm.passRate === 1 && lm.flaky === 0 && lm.failed === 0) {
    out.push('- Note: a 100% pass rate describes this execution only; it is not evidence of absence of risk.');
  }
  out.push('');

  // ---- Trends ----
  const trends = computeTrends(runs);
  out.push('## Trends');
  out.push('');
  if (trends.insufficientData || trends.delta === null) {
    out.push(`**Insufficient data** — ${trends.cohortSize} comparable run(s) in the latest run's cohort; trends require ≥2.`);
    for (const n of trends.notes) out.push(`- ${n}`);
  } else {
    out.push(`Comparability cohort: ${trends.cohortSize} run(s) (same project set and spec files).`);
    out.push('');
    out.push('| Metric | Previous → Latest | Delta |');
    out.push('| ------ | ----------------- | ----- |');
    out.push(`| pass rate | \`${trends.delta.previousRunId}\` → \`${trends.delta.latestRunId}\` | ${signedPct(trends.delta.passRateDelta)} |`);
    out.push(`| run duration | | ${signedMs(trends.delta.runDurationDeltaMs)} |`);
    out.push(`| test duration Σ | | ${signedMs(trends.delta.testDurationDeltaMs)} |`);
    for (const n of trends.notes) out.push(`- ${n}`);
    out.push('');
    out.push('_Deltas describe change between two executions; they do not establish cause._');
  }
  out.push('');

  // ---- Flakiness ----
  const flakiness = computeTestFlakiness(runs);
  const flakyRows = flakiness.filter((f) => f.flakyCount > 0);
  out.push('## Per-test flakiness (comparable cohort)');
  out.push('');
  if (flakiness.length === 0) {
    out.push('**Insufficient data** — no executed tests in the comparability cohort.');
  } else if (flakyRows.length === 0) {
    out.push(`No flaky tests observed across ${trends.cohortSize || flakiness.length > 0 ? 'the' : ''} comparable run(s). This does not prove absence of flakiness.`);
  } else {
    out.push('| Test | Project | Appearances | Flaky | Flaky rate | Sample |');
    out.push('| ---- | ------- | ----------- | ----- | ---------- | ------ |');
    for (const f of flakyRows) {
      out.push(
        `| ${esc(f.title)} | ${f.project} | ${f.appearances} | ${f.flakyCount} | ${pct(f.flakyRate)} | ${f.lowSample ? 'low (<5)' : 'ok'} |`,
      );
    }
  }
  out.push('');

  // ---- Data quality ----
  const partial = runs.filter((r) => r.run.completeness !== 'complete');
  out.push('## Data quality');
  out.push('');
  out.push(`- Runs with completeness ≠ complete: **${partial.length}**`);
  for (const r of partial) {
    out.push(`  - \`${r.run.runId}\`: ${r.run.completeness} — ${r.run.completenessReason ?? 'no reason recorded'}`);
  }
  out.push(`- Non-processable files: **${nonProcessable.length}**`);
  for (const n of nonProcessable) {
    out.push(`  - \`${n.file}\`: ${n.issues.map((i) => `${i.path}: ${i.message}`).join('; ')}`);
  }
  if (partial.length === 0 && nonProcessable.length === 0) {
    out.push('- All runs validated cleanly against contract v1.');
  }
  out.push('');

  // ---- Definitions ----
  out.push('## Metric definitions');
  out.push('');
  for (const [name, def] of DEFS) out.push(`- **${name}** — ${def}`);
  out.push('');

  return out.join('\n');
}
